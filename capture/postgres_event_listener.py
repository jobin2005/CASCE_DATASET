"""
postgres_event_listener.py

Listens to PostgreSQL telemetry events generated by the pg_telemetry
extension and forwards each event to EventBus immediately.
"""

import json
import os
import sys
import threading
import time
from pathlib import Path
from typing import Optional

DEFAULT_PG_LOG_PATH = "/dataset_workspace/postgres_events.json"

_listener_thread: Optional[threading.Thread] = None
_running = False


def _tail_log_file(log_path: Path, event_bus):
    global _running

    # Seek to end or beginning depending on whether file exists
    pos = 0
    if log_path.exists():
        pos = log_path.stat().st_size

    while _running:
        if not log_path.exists():
            time.sleep(0.05)
            continue

        with log_path.open("r", encoding="utf-8", errors="ignore") as f:
            f.seek(pos)
            lines = f.readlines()
            pos = f.tell()

        for line in lines:
            line = line.strip()
            if not line:
                continue
            try:
                raw_event = json.loads(line)
            except Exception:
                continue

            # Skip markers like LOGGING_START / LOGGING_STOP
            if "marker" in raw_event:
                continue

            ts = float(raw_event.get("timestamp", time.time()))
            backend_pid = raw_event.get("backend_pid") or raw_event.get("session_id", 0)
            session_id = raw_event.get("session_id", backend_pid)

            normalized_event = {
                "source": "postgres",
                "timestamp": ts,
                "timestamp_unix": ts,
                "pid": int(backend_pid),
                "session_key": int(session_id),
                "query": raw_event.get("query", ""),
                "database": raw_event.get("database", ""),
                "username": raw_event.get("username", ""),
                "client_addr": raw_event.get("client_addr", ""),
                "client_port": raw_event.get("client_port", ""),
                "event_type": raw_event.get("event_type", ""),
                "raw": raw_event,
            }
            event_bus.publish(normalized_event)

        time.sleep(0.05)


def start_listener(event_bus, log_path: Optional[str] = None, dsn: Optional[str] = None):
    """
    Starts listening on the PostgreSQL telemetry channel (file tailing or socket)
    and forwards incoming events to event_bus.
    """
    global _listener_thread, _running

    if _running:
        return

    _running = True
    target_path = Path(log_path or os.environ.get("CASCE_PG_LOG", DEFAULT_PG_LOG_PATH))

    # Ensure parent directory exists
    try:
        target_path.parent.mkdir(parents=True, exist_ok=True)
    except Exception:
        pass

    _listener_thread = threading.Thread(
        target=_tail_log_file, args=(target_path, event_bus), daemon=True
    )
    _listener_thread.start()


def stop_listener():
    """Stops the PostgreSQL event listener cleanly."""
    global _listener_thread, _running
    _running = False
    if _listener_thread and _listener_thread.is_alive():
        _listener_thread.join(timeout=1.0)
    _listener_thread = None
